    ("course-audit",
     r"достаточно ли|хватит ли|чего не хватает|курс правильный|что ещ[её] добавить",
     "проверка курса на полноту против целей «гипервизор» и «работа»"),
    ("write-appendix",
     r"приложени|\bп[5-9]\b|python для|питон|c\+\+|\bраст\b|\brust\b|"
     r"сетев\w* трафик|трафик|wireshark|ida pro 9",
     "приложение П5–П9: IDA Pro, Python, C++, Rust, сетевой трафик"),
